/**
 * Collects the About page's build info from the filesystem and git — see
 * `build-info.ts` for what it holds. Runs once, from next.config.ts, while
 * `next build` (or `next dev`) loads the config; the About page never touches
 * git or the filesystem at runtime (Vercel's serverless functions have
 * neither).
 *
 * Commit metadata prefers Vercel's `VERCEL_GIT_*` env vars and falls back to
 * local `git`. Vercel clones shallowly, so anything that needs full history
 * (commit count, first commit date) comes back `null` on a shallow clone
 * rather than a misleadingly small number; the page hides those rows.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { extname, join, relative } from "node:path";

import {
  type BuildInfo,
  type CoverageStats,
  type CoverageSummary,
  LANGUAGES,
  type SourceFile,
  summarizeCodebase,
  summarizeCoverage,
} from "./build-info";

// Directories that hold hand-written source; generated output (.next,
// node_modules) never appears under these.
const SOURCE_DIRS = ["src", "supabase", "scripts", "public"];
const SKIP_DIRS = new Set(["node_modules", ".temp", ".next", "icons"]);
// Generated by `supabase gen types` — counting it would inflate TypeScript
// by several hundred lines nobody wrote.
const SKIP_FILES = new Set(["src/lib/supabase/database.types.ts"]);

/**
 * Reads the report `pnpm build` produces by running `pnpm test:coverage`
 * first. Vitest clears the report directory at the start of a run and writes
 * no report when a test fails, so a failed run leaves nothing here and the
 * About page shows coverage as unavailable rather than a stale number.
 */
function readCoverage(root: string): CoverageStats | null {
  const summary = readJson(join(root, "coverage", "coverage-summary.json"));
  return summary ? summarizeCoverage(summary as CoverageSummary, root) : null;
}

function walk(root: string, dir: string, out: SourceFile[]) {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      walk(root, full, out);
      continue;
    }
    const path = relative(root, full).split("\\").join("/");
    if (SKIP_FILES.has(path) || !LANGUAGES[extname(path)]) continue;
    out.push({ path, content: readFileSync(full, "utf8") });
  }
}

function git(root: string, ...args: string[]): string | null {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

function readJson(path: string): Record<string, unknown> | null {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

function installedVersion(root: string, pkg: string): string | null {
  const json = readJson(join(root, "node_modules", pkg, "package.json"));
  return typeof json?.version === "string" ? json.version : null;
}

function safeList(dir: string): string[] {
  try {
    return readdirSync(dir);
  } catch {
    return [];
  }
}

export function collectBuildInfo(root: string): BuildInfo {
  const env = process.env;
  const sha = env.VERCEL_GIT_COMMIT_SHA || git(root, "rev-parse", "HEAD");
  const shallow = git(root, "rev-parse", "--is-shallow-repository") !== "false";

  const files: SourceFile[] = [];
  for (const dir of SOURCE_DIRS) walk(root, join(root, dir), files);
  const docPaths = [
    join(root, "README.md"),
    join(root, "durak-tracker-spec.md"),
    ...safeList(join(root, "docs")).map((name) => join(root, "docs", name)),
  ];
  const docs: string[] = [];
  for (const path of docPaths) {
    if (!path.endsWith(".md")) continue;
    try {
      docs.push(readFileSync(path, "utf8"));
    } catch {
      // Missing doc — just skip it.
    }
  }

  const pkg = readJson(join(root, "package.json")) ?? {};
  const depCount = (key: string) =>
    Object.keys((pkg[key] as Record<string, string> | undefined) ?? {}).length;

  return {
    commitSha: sha,
    commitShortSha: sha ? sha.slice(0, 7) : null,
    commitMessage:
      env.VERCEL_GIT_COMMIT_MESSAGE?.split("\n")[0] ||
      git(root, "log", "-1", "--format=%s"),
    commitDate: git(root, "log", "-1", "--format=%cI"),
    branch:
      env.VERCEL_GIT_COMMIT_REF ||
      git(root, "rev-parse", "--abbrev-ref", "HEAD"),
    builtAt: new Date().toISOString(),
    commitCount: shallow
      ? null
      : Number(git(root, "rev-list", "--count", "HEAD")) || null,
    firstCommitDate: shallow
      ? null
      : (git(root, "log", "--reverse", "--format=%cI")?.split("\n")[0] ?? null),
    dependencies: depCount("dependencies"),
    devDependencies: depCount("devDependencies"),
    nextVersion: installedVersion(root, "next"),
    reactVersion: installedVersion(root, "react"),
    tailwindVersion: installedVersion(root, "tailwindcss"),
    supabaseJsVersion: installedVersion(root, "@supabase/supabase-js"),
    code: summarizeCodebase(files, docs),
    coverage: readCoverage(root),
  };
}
